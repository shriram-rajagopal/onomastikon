// Builds the tiny "Endonyms" webfont: every language's native_name, and
// nothing else, subset out of the self-hosted Noto/Garamond faces. The
// homepage renders each language's self-name in its own script; doing that
// with the full script fonts would cost over a megabyte (cuneiform alone is
// ~460 KB), while the union of all endonym glyphs fits in a few KB per script.
//
// Emits public/fonts/endonyms-<face>.woff2 plus src/styles/endonyms.css with
// one @font-face per face under the single family 'Endonyms', each keeping
// its source's unicode-range. Consumers put 'Endonyms' first in the stack and
// the full script fonts after it, so an endonym added before this script runs
// still renders (at full-font cost) rather than breaking.
//
// Wired as npm run build's prebuild, so it stays current with the content;
// fail-soft by design — a subsetting problem warns and keeps going.
import subsetFont from 'subset-font';
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// The same faces BaseLayout imports; the subsetter only keeps faces whose
// unicode-range actually covers endonym characters.
const PACKAGES = [
  'eb-garamond',
  'noto-sans-egyptian-hieroglyphs',
  'noto-sans-cuneiform',
  'noto-sans-old-persian',
  'noto-sans-avestan',
  'noto-serif-devanagari',
  'noto-serif-hebrew',
  'noto-naskh-arabic',
  'noto-sans-coptic',
  'noto-sans-ethiopic',
  'noto-sans-inscriptional-pahlavi',
  'noto-sans-inscriptional-parthian',
  'noto-sans-manichaean',
  'noto-sans-syriac',
  'noto-sans-phoenician',
  'noto-sans-ugaritic',
  'noto-sans-lycian',
  'noto-serif-armenian',
  'noto-sans-old-italic',
  'noto-sans-linear-b',
];

// Union of endonym characters, in both compositions so precomposed and
// combining-mark renderings are both covered.
const langDir = join(root, 'src/content/languages');
let text = '';
for (const file of readdirSync(langDir).filter((f) => f.endsWith('.md'))) {
  const m = readFileSync(join(langDir, file), 'utf8').match(/^native_name:\s*(.+)$/m);
  if (m) {
    const name = m[1].trim().replace(/^['"]|['"]$/g, '');
    text += name.normalize('NFC') + name.normalize('NFD');
  }
}
const codepoints = new Set([...text].map((c) => c.codePointAt(0)));

const inRanges = (ranges) =>
  [...codepoints].some((cp) =>
    ranges.some(([lo, hi]) => cp >= lo && cp <= hi)
  );

const parseRanges = (spec) =>
  spec.split(',').map((r) => {
    const m = r.trim().match(/^U\+([0-9A-F?]+)(?:-([0-9A-F]+))?$/i);
    if (!m) return [0, -1];
    if (m[1].includes('?')) {
      const lo = parseInt(m[1].replaceAll('?', '0'), 16);
      const hi = parseInt(m[1].replaceAll('?', 'F'), 16);
      return [lo, hi];
    }
    const lo = parseInt(m[1], 16);
    return [lo, m[2] ? parseInt(m[2], 16) : lo];
  });

const outDir = join(root, 'public/fonts');
mkdirSync(outDir, { recursive: true });
const faces = [];
let total = 0;

for (const pkg of PACKAGES) {
  const cssPath = join(root, 'node_modules/@fontsource', pkg, '400.css');
  let css;
  try {
    css = readFileSync(cssPath, 'utf8');
  } catch {
    console.warn(`endonyms: ${pkg} not installed, skipping`);
    continue;
  }
  for (const block of css.split('@font-face').slice(1)) {
    const url = block.match(/url\(\.\/files\/([^)]+\.woff2)\)/)?.[1];
    const range = block.match(/unicode-range:\s*([^;]+);/)?.[1];
    if (!url || !range || !inRanges(parseRanges(range))) continue;
    // Every Noto package also ships latin/math/symbol subsets whose ranges any
    // Latin-script endonym would match, which would yield dozens of duplicate
    // faces (and let a Noto face shadow Garamond for Latin text). Keep each
    // Noto package's script subsets only; Garamond covers Latin and Greek.
    const subsetName = url.replace(`${pkg}-`, '').replace(/-400-normal\.woff2$/, '');
    const GENERIC = ['latin', 'latin-ext', 'math', 'symbols', 'cyrillic', 'cyrillic-ext', 'vietnamese'];
    const keep =
      pkg === 'eb-garamond'
        ? ['latin', 'latin-ext', 'greek', 'greek-ext'].includes(subsetName)
        : !GENERIC.includes(subsetName);
    if (!keep) continue;
    try {
      const source = readFileSync(join(root, 'node_modules/@fontsource', pkg, 'files', url));
      const subset = await subsetFont(source, text, { targetFormat: 'woff2' });
      const name = `endonyms-${url.replace(/-400-normal\.woff2$/, '')}.woff2`;
      writeFileSync(join(outDir, name), subset);
      faces.push({ name, range });
      total += subset.length;
    } catch (err) {
      console.warn(`endonyms: failed on ${pkg}/${url}: ${err.message}`);
    }
  }
}

const cssOut = [
  '/* Generated by scripts/subset-endonyms.mjs — do not edit. The homepage',
  "   endonym column uses family 'Endonyms': every language's self-name,",
  '   subset to just those glyphs. Regenerated on every build (prebuild). */',
  ...faces.map(
    (f) => `@font-face {
  font-family: 'Endonyms';
  font-style: normal;
  font-weight: 400;
  font-display: swap;
  src: url(/fonts/${f.name}) format('woff2');
  unicode-range: ${f.range};
}`
  ),
  '',
].join('\n');
writeFileSync(join(root, 'src/styles/endonyms.css'), cssOut);
console.log(
  `endonyms: ${faces.length} faces, ${(total / 1024).toFixed(1)}K total, ${codepoints.size} codepoints`
);
